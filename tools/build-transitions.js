// Builds app/vendor/gl-transitions.js from the gl-transitions npm package (MIT).
//   npm pack gl-transitions && tar xzf gl-transitions-*.tgz
//   node tools/build-transitions.js package/gl-transitions.json [skip-list.json]
// Transitions that need extra picture inputs are left out, and so is any name in the skip list
// (the ones that failed to compile in WebGL 1 when tested).
const fs = require('fs');
const path = require('path');
const src = process.argv[2];
const skip = new Set(process.argv[3] ? JSON.parse(fs.readFileSync(process.argv[3], 'utf8')) : []);
const all = JSON.parse(fs.readFileSync(src, 'utf8'));
const out = [];
for (const t of all) {
  if ((t.textures && t.textures.length) || skip.has(t.name)) continue;
  const params = {};
  for (const [k, p] of Object.entries(t.params || {})) {
    const d = p.default !== undefined ? p.default : (t.defaultParams || {})[k];
    params[k] = [p.type || t.paramsTypes[k], d];
  }
  out.push({ name: t.name, author: t.author, license: t.license, tags: t.tags, params, glsl: t.glsl });
}
const dir = path.join(__dirname, '..', 'app', 'vendor');
fs.writeFileSync(path.join(dir, 'gl-transitions.js'),
  '/* GL Transitions, https://github.com/gl-transitions/gl-transitions (MIT, see gl-transitions.LICENSE). Generated by tools/build-transitions.js */\n' +
  'window.GL_TRANSITIONS = ' + JSON.stringify(out) + ';\n');
const lic = fs.readFileSync(path.join(path.dirname(src), 'LICENSE'), 'utf8');
fs.writeFileSync(path.join(dir, 'gl-transitions.LICENSE'), lic + '\n\nEach transition keeps its own license and author line at the top of its shader.\nAuthors and licenses of the transitions included in Cliploom:\n\n' +
  out.map((t) => t.name + ': ' + t.author + ' (' + t.license + ')').join('\n') + '\n');
console.log(out.length + ' transitions written');
